// ============================================================
// 双指针 (Two Pointers) — 题目框架
// ============================================================
// 三种模式：
//   1. 左右指针 (相向而行) — 有序数组
//   2. 快慢指针 (同向而行) — 原地修改
//   3. 定一移二 (固定 + 双向) — 多元素组合
// ============================================================

#include <algorithm>
#include <iostream>
#include <vector>
using namespace std;

// ============================================================
// 模式一：左右指针
// ============================================================

// LC 167 — 两数之和 II (有序数组) 🟢
// 思路：左右指针向中间逼近
vector<int> twoSum(vector<int> &numbers, int target);

// LC 11 — 盛最多水的容器 🟠
// 思路：左右指针，移动较短的边
int maxArea(vector<int> &height);

// ============================================================
// 模式二：快慢指针
// ============================================================

// LC 26 — 删除有序数组重复项 🟢
// 思路：slow 标记不重复元素的位置
int removeDuplicates(vector<int> &nums);

// LC 27 — 移除元素 🟢
// 思路：slow 标记非 val 元素的位置
int removeElement(vector<int> &nums, int val);

// LC 283 — 移动零 🟢
// 思路：非零元素往前放，末尾补零
void moveZeroes(vector<int> &nums);

// ============================================================
// 模式三：定一移二
// ============================================================

// LC 15 — 三数之和 🟠
// 思路：排序 + 固定 i + 左右双指针，三重去重
vector<vector<int>> threeSum(vector<int> &nums);

