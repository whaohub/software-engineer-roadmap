//
// 固定套路：
//   ListNode *slow = head, *fast = head;
//   while (fast != nullptr && fast->next != nullptr) {
//     slow = slow->next;          // 1 倍速
//     fast = fast->next->next;    // 2 倍速
//   }
//
// 易错点：循环条件必须先判 fast 非空、再判 fast->next 非空，
//        然后才能取 fast->next->next（短路求值顺序不能颠倒）
// ============================================================

